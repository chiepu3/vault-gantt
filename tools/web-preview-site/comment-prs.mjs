// Creates/updates ONE sticky preview comment per open PR target. Edits only when content changed.
// Usage: node comment-prs.mjs --targets site/targets.json [--dry-run]   (needs GH_TOKEN, `gh`)
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { parseArgs, previewUrl } from "./common.mjs";

const args = parseArgs(process.argv.slice(2));
const plan = JSON.parse(readFileSync(args.targets, "utf8"));
const repo = plan.repository;
const MARKER = "<!-- vault-gantt-preview -->";
const gh = (a, input) => execFileSync("gh", a, { encoding: "utf8", input, maxBuffer: 64 << 20 });

export function commentBody(t) {
  const st = t.status === "success" ? "成功" : "失敗";
  return `${MARKER}
ブラウザプレビュー: ${previewUrl(repo, t.slug)}

- コミット: \`${t.sha.slice(0, 7)}\`
- ビルド: ${st}${t.status === "success" ? "" : `(${t.error || "エラー"})`}

---
_Generated by [Claude Code](https://claude.ai/code)_
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const t of plan.targets.filter((x) => x.pr)) {
    const body = commentBody(t);
    const comments = JSON.parse(gh(["api", "--paginate", "--slurp", `repos/${repo}/issues/${t.pr.number}/comments?per_page=100`])).flat();
    const mine = comments.find((c) => c.body?.includes(MARKER));
    if (args["dry-run"]) { console.log(`#${t.pr.number}: ${mine ? "update" : "create"}\n${body}`); continue; }
    const payload = JSON.stringify({ body });
    if (!mine) { gh(["api", "-X", "POST", `repos/${repo}/issues/${t.pr.number}/comments`, "--input", "-"], payload); console.log(`#${t.pr.number}: created`); }
    else if (mine.body.trim() !== body.trim()) { gh(["api", "-X", "PATCH", `repos/${repo}/issues/comments/${mine.id}`, "--input", "-"], payload); console.log(`#${t.pr.number}: updated`); }
    else console.log(`#${t.pr.number}: unchanged`);
  }
}
