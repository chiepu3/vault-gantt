/**
 * In-plugin updater: lists the branches CI has built (GitHub Pages `targets.json`), downloads the built
 * main.js / manifest.json / styles.css of the chosen one, replaces the installed files (keeping a `.backup/`
 * copy, same layout as tools/updater/Quick-Install.ps1) and reloads the plugin. No git or node needed on the PC.
 */

export const UPDATE_SITE_BASE = "https://chiepu3.github.io/vault-gantt";
export const PLUGIN_FILES = ["main.js", "manifest.json", "styles.css"] as const;
export const BACKUP_DIR = ".backup";

export interface UpdateTarget {
  branch: string;
  slug: string;
  sha: string;
  kind: "main" | "all" | "pr";
  pr: { number: number; title: string } | null;
  commitTime: string | null;
}

interface PluginMeta {
  branch: string;
  sha: string;
  version: string;
  builtAt: string;
  files: Record<string, { size: number; sha256: string }>;
}

export interface HttpResponse { status: number; arrayBuffer: ArrayBuffer }
export type HttpGet = (url: string) => Promise<HttpResponse>;

/** The subset of Obsidian's DataAdapter used here. */
export interface UpdateAdapter {
  exists(path: string): Promise<boolean>;
  mkdir(path: string): Promise<void>;
  readBinary(path: string): Promise<ArrayBuffer>;
  writeBinary(path: string, data: ArrayBuffer): Promise<void>;
}

export interface SelfUpdateDeps {
  http: HttpGet;
  adapter: UpdateAdapter;
  /** Vault-relative plugin folder, e.g. `.obsidian/plugins/vault-gantt`. */
  pluginDir: string;
  siteBase?: string;
  sha256Hex?: (data: ArrayBuffer) => Promise<string>;
}

export async function defaultSha256Hex(data: ArrayBuffer): Promise<string> {
  const digest = await crypto.subtle.digest("SHA-256", data);
  return Array.from(new Uint8Array(digest), (b) => b.toString(16).padStart(2, "0")).join("");
}

function decodeJson(buffer: ArrayBuffer): unknown {
  return JSON.parse(new TextDecoder().decode(buffer));
}

/** Slugs are generated by CI; refuse anything that could leave `b/<slug>/`. */
function isSafeSlug(slug: unknown): slug is string {
  return typeof slug === "string" && /^[A-Za-z0-9._-]+$/.test(slug) && !slug.startsWith(".");
}

export function targetLabel(t: UpdateTarget): string {
  const base = t.kind === "main" ? `${t.branch}（最新の正式版）` : t.branch;
  return t.pr ? `${base} — #${t.pr.number} ${t.pr.title}` : base;
}

/** main first, then `*-all` evaluation branches, then PRs, newest commit first within each group. */
export function sortTargets(targets: UpdateTarget[]): UpdateTarget[] {
  const rank = { main: 0, all: 1, pr: 2 } as const;
  return [...targets].sort(
    (a, b) => rank[a.kind] - rank[b.kind] || String(b.commitTime ?? "").localeCompare(String(a.commitTime ?? ""))
  );
}

export class SelfUpdater {
  private readonly siteBase: string;
  private readonly sha256Hex: (data: ArrayBuffer) => Promise<string>;

  constructor(private readonly deps: SelfUpdateDeps) {
    this.siteBase = (deps.siteBase ?? UPDATE_SITE_BASE).replace(/\/+$/, "");
    this.sha256Hex = deps.sha256Hex ?? defaultSha256Hex;
  }

  private async get(url: string): Promise<ArrayBuffer> {
    const res = await this.deps.http(url);
    if (res.status < 200 || res.status >= 300) throw new Error(`ダウンロードに失敗しました（HTTP ${res.status}）: ${url}`);
    return res.arrayBuffer;
  }

  /** Branches CI has built an installable bundle for. */
  async listTargets(): Promise<UpdateTarget[]> {
    const json = decodeJson(await this.get(`${this.siteBase}/targets.json?t=${Date.now()}`)) as { targets?: unknown };
    const raw = Array.isArray(json.targets) ? (json.targets as Record<string, unknown>[]) : [];
    const targets: UpdateTarget[] = [];
    for (const t of raw) {
      if (t.status !== "success" || t.plugin !== true || !isSafeSlug(t.slug) || typeof t.branch !== "string" || typeof t.sha !== "string") continue;
      const kind = t.kind === "main" || t.kind === "all" ? t.kind : "pr";
      const pr = t.pr as { number?: unknown; title?: unknown } | null | undefined;
      targets.push({
        branch: t.branch,
        slug: t.slug,
        sha: t.sha,
        kind,
        pr: pr && typeof pr.number === "number" ? { number: pr.number, title: String(pr.title ?? "") } : null,
        commitTime: typeof t.commitTime === "string" ? t.commitTime : null,
      });
    }
    return sortTargets(targets);
  }

  /** Downloads, verifies and installs `target`. Existing files are copied to `.backup/` first and restored if writing fails. */
  async install(target: UpdateTarget): Promise<{ version: string; sha: string }> {
    if (!isSafeSlug(target.slug)) throw new Error("不正なブランチ名です。");
    const base = `${this.siteBase}/b/${target.slug}/plugin`;
    const meta = decodeJson(await this.get(`${base}/meta.json?t=${Date.now()}`)) as PluginMeta;
    const downloaded = new Map<string, ArrayBuffer>();
    for (const name of PLUGIN_FILES) {
      const expected = meta.files?.[name];
      if (!expected) throw new Error(`${name} の情報が見つかりません。`);
      const data = await this.get(`${base}/${name}?v=${encodeURIComponent(meta.sha)}`);
      if (data.byteLength === 0 || data.byteLength !== expected.size) throw new Error(`${name} のサイズが一致しません。ダウンロードをやり直してください。`);
      if ((await this.sha256Hex(data)) !== expected.sha256) throw new Error(`${name} のチェックサムが一致しません。ダウンロードをやり直してください。`);
      downloaded.set(name, data);
    }
    const manifest = decodeJson(downloaded.get("manifest.json") as ArrayBuffer) as { id?: unknown; version?: unknown };
    if (manifest.id !== "vault-gantt") throw new Error("Vault Gantt のファイルではありません。");

    await this.backupCurrent();
    try {
      for (const name of PLUGIN_FILES) await this.deps.adapter.writeBinary(`${this.deps.pluginDir}/${name}`, downloaded.get(name) as ArrayBuffer);
    } catch (error) {
      await this.restoreBackup().catch(() => undefined);
      throw error;
    }
    return { version: String(manifest.version ?? meta.version), sha: meta.sha };
  }

  private async backupCurrent(): Promise<void> {
    const { adapter, pluginDir } = this.deps;
    const backup = `${pluginDir}/${BACKUP_DIR}`;
    if (!(await adapter.exists(backup))) await adapter.mkdir(backup);
    for (const name of PLUGIN_FILES) {
      if (await adapter.exists(`${pluginDir}/${name}`)) await adapter.writeBinary(`${backup}/${name}`, await adapter.readBinary(`${pluginDir}/${name}`));
    }
  }

  async hasBackup(): Promise<boolean> {
    return this.deps.adapter.exists(`${this.deps.pluginDir}/${BACKUP_DIR}/main.js`);
  }

  /** Copies `.backup/` (the files before the last install) back over the installed ones. */
  async restoreBackup(): Promise<void> {
    const { adapter, pluginDir } = this.deps;
    const backup = `${pluginDir}/${BACKUP_DIR}`;
    for (const name of PLUGIN_FILES) {
      if (await adapter.exists(`${backup}/${name}`)) await adapter.writeBinary(`${pluginDir}/${name}`, await adapter.readBinary(`${backup}/${name}`));
    }
  }
}
